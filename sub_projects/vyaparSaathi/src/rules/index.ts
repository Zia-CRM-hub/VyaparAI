/** Special-category states have lower GST registration limits. */
const SPECIAL_CATEGORY = new Set(["AR", "MN", "MZ", "NL", "SK", "TR", "UK", "HP", "ML", "JK"]);
export function gstThreshold(p: BusinessProfile): number {
  const special = SPECIAL_CATEGORY.has(p.state);
  if (p.supply === "services") return special ? 1_000_000 : 2_000_000;
  return special ? 2_000_000 : 4_000_000; // goods and "both": the goods limit applies
}

